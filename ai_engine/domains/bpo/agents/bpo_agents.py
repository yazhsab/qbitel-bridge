        # Check for after-hours access
        after_hours = [l for l in access_logs if l.get("hour", 12) < 6 or l.get("hour", 12) > 22]
        if len(after_hours) > 10:
            anomalies.append({
                "type": "after_hours_access",
                "description": f"{len(after_hours)} after-hours CRM accesses",
                "severity": "medium",
            })

        return {
            "total_accesses": total_accesses,
            "anomalies": anomalies,
            "time_window_hours": time_window,
        }


