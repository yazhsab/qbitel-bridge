class BaseBPOAgent(ABC):
    """
    Base class for all BPO specialized agents.

    Provides common functionality for BPO agents including alert generation,
    compliance tracking, and integration with BPO security modules.

    Note: In production, this would inherit from ai_engine.agents.base_agent.BaseAgent.
    Here we implement the core interface to avoid circular imports while maintaining
    full compatibility with the platform's agent orchestrator.
    """

    def __init__(self, config: BPOAgentConfig):
        """Initialize the BPO agent."""
        self.agent_id = str(uuid.uuid4())
        self.config = config
        self.agent_type = config.agent_type.value
        self.status = "idle"
        self._running = False
        self._alerts: List[BPOAlert] = []
        self._task_count = 0
        self._error_count = 0
        self.created_at = datetime.utcnow()
        self.logger = logging.getLogger(f"{__name__}.{config.agent_type.value}.{self.agent_id[:8]}")
        self.logger.info(f"BPO Agent initialized: {self.agent_type}")

    async def start(self) -> None:
        """Start the agent."""
        self._running = True
        self.status = "idle"
        await self._on_start()
        self.logger.info(f"BPO Agent started: {self.agent_type}")

    async def stop(self) -> None:
        """Stop the agent."""
        self._running = False
        self.status = "terminated"
        await self._on_stop()
        self.logger.info(f"BPO Agent stopped: {self.agent_type}")

    async def execute(self, task_type: str, payload: Dict[str, Any]) -> Dict[str, Any]:
        """
        Execute a task.

        Args:
            task_type: Type of task to execute
            payload: Task payload

        Returns:
            Task result dictionary
        """
        start_time = time.time()
        self.status = "busy"
        self._task_count += 1

        try:
            result = await self._execute_task(task_type, payload)
            duration = time.time() - start_time

            BPO_AGENT_TASKS.labels(
                agent_type=self.agent_type, task_type=task_type, status="success"
            ).inc()
            BPO_AGENT_DURATION.labels(
                agent_type=self.agent_type, task_type=task_type
            ).observe(duration)

            self.status = "idle"
            return {
                "success": True,
                "result": result,
                "duration": duration,
                "agent_id": self.agent_id,
                "agent_type": self.agent_type,
            }

        except Exception as e:
            duration = time.time() - start_time
            self._error_count += 1

            BPO_AGENT_TASKS.labels(
                agent_type=self.agent_type, task_type=task_type, status="error"
            ).inc()

            self.status = "error"
            self.logger.error(f"Task failed: {task_type} - {e}")
            return {
                "success": False,
                "error": str(e),
                "duration": duration,
                "agent_id": self.agent_id,
                "agent_type": self.agent_type,
            }

    def generate_alert(
        self,
        severity: AlertSeverity,
        title: str,
        description: str,
        affected_resource: str = "",
        recommended_action: str = "",
        compliance_impact: Optional[List[str]] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> BPOAlert:
        """Generate and store an alert."""
        alert = BPOAlert(
            agent_type=self.agent_type,
            severity=severity,
            title=title,
            description=description,
            affected_resource=affected_resource,
            recommended_action=recommended_action,
            compliance_impact=compliance_impact or [],
            metadata=metadata or {},
        )

        self._alerts.append(alert)

        BPO_AGENT_ALERTS.labels(
            agent_type=self.agent_type, severity=severity.value
        ).inc()

        self.logger.warning(f"Alert [{severity.value}]: {title}")

        # Keep only last 10000 alerts
        if len(self._alerts) > 10000:
            self._alerts = self._alerts[-10000:]

        return alert

    def get_alerts(
        self,
        severity: Optional[AlertSeverity] = None,
        since: Optional[datetime] = None,
        limit: int = 100,
    ) -> List[BPOAlert]:
        """Get alerts, optionally filtered."""
        alerts = self._alerts
        if severity:
            alerts = [a for a in alerts if a.severity == severity]
        if since:
            alerts = [a for a in alerts if a.timestamp >= since.isoformat()]
        return alerts[-limit:]

    def get_status(self) -> Dict[str, Any]:
        """Get agent status."""
        return {
            "agent_id": self.agent_id,
            "agent_type": self.agent_type,
            "status": self.status,
            "task_count": self._task_count,
            "error_count": self._error_count,
            "alert_count": len(self._alerts),
            "created_at": self.created_at.isoformat(),
        }

    async def _on_start(self) -> None:
        """Override for custom start logic."""
        pass

    async def _on_stop(self) -> None:
        """Override for custom stop logic."""
        pass

    async def _execute_task(self, task_type: str, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Override to implement task execution."""
        raise NotImplementedError(f"Task type {task_type} not implemented")


