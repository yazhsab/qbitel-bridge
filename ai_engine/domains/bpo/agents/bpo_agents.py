BPO_AGENT_REGISTRY: Dict[str, type] = {
    BPOAgentType.CALL_PROCESSING.value: CallProcessingAgent,
    BPOAgentType.PCI_COMPLIANCE.value: PCIComplianceAgent,
    BPOAgentType.FRAUD_DETECTION.value: FraudDetectionAgent,
    BPOAgentType.CRM_SCREEN_POP.value: CRMScreenPopAgent,
    BPOAgentType.RECORDING_ENCRYPTION.value: RecordingEncryptionAgent,
    BPOAgentType.SESSION_SECURITY.value: SessionSecurityAgent,
    BPOAgentType.REMOTE_ACCESS.value: RemoteAccessAgent,
    BPOAgentType.COMPLIANCE_AUDIT.value: ComplianceAuditAgent,
}


def create_agent(agent_type: str, config: Optional[BPOAgentConfig] = None) -> BaseBPOAgent:
    """
    Factory method to create a BPO agent by type.

    Args:
        agent_type: BPO agent type string
        config: Optional agent configuration

    Returns:
        Instantiated BPO agent
    """
    agent_class = BPO_AGENT_REGISTRY.get(agent_type)
    if not agent_class:
        raise ValueError(f"Unknown BPO agent type: {agent_type}. Available: {list(BPO_AGENT_REGISTRY.keys())}")
    return agent_class(config)


def get_agent_types() -> List[str]:
    """Get all available BPO agent types."""
    return list(BPO_AGENT_REGISTRY.keys())
