class CallProcessingAgent(BaseBPOAgent):
    """
    Real-time call security monitoring and anomaly detection.

    Capabilities:
    - SIP signaling analysis for call setup/teardown anomalies
    - Real-time voice quality monitoring
    - Call pattern analysis and anomaly detection
    - SIP header validation and spoofing detection
    - Media path monitoring (RTP/SRTP verification)
    """

    def __init__(self, config: Optional[BPOAgentConfig] = None):
        if config is None:
            config = BPOAgentConfig(agent_type=BPOAgentType.CALL_PROCESSING)
        super().__init__(config)

        # Call processing state
        self._active_calls: Dict[str, Dict[str, Any]] = {}
        self._call_patterns: Dict[str, List[Dict[str, Any]]] = {}
        self._anomaly_threshold: float = 0.75

    async def _execute_task(self, task_type: str, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Execute call processing tasks."""
        if task_type == TaskType.ANALYZE_CALL.value:
            return await self._analyze_call(payload)
        elif task_type == TaskType.MONITOR_SIGNALING.value:
            return await self._monitor_signaling(payload)
        elif task_type == TaskType.DETECT_ANOMALY.value:
            return await self._detect_anomaly(payload)
        else:
            raise ValueError(f"Unknown task type: {task_type}")

    async def _analyze_call(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Analyze a call for security concerns."""
        call_id = payload.get("call_id", "unknown")
        sip_headers = payload.get("sip_headers", {})
        direction = payload.get("direction", "inbound")

        findings = []
        risk_score = 0.0

        # Validate From/To headers
        from_header = sip_headers.get("From", "")
        to_header = sip_headers.get("To", "")

        if not from_header or not to_header:
            findings.append("Missing From/To headers")
            risk_score += 0.3

        # Check for SIP URI spoofing patterns
        if "@" not in from_header:
            findings.append("Malformed From URI - possible spoofing")
            risk_score += 0.4

        # Validate Via hop count
        via_hops = sip_headers.get("via_hops", 0)
        if via_hops > 10:
            findings.append(f"Excessive Via hops ({via_hops}) - possible loop")
            risk_score += 0.3

        # Check for media encryption
        media_encrypted = payload.get("media_encrypted", False)
        if not media_encrypted:
            findings.append("Call using unencrypted RTP")
            risk_score += 0.2

        # Check for PQC
        pqc_enabled = payload.get("pqc_enabled", False)

        if risk_score > self._anomaly_threshold:
            self.generate_alert(
                severity=AlertSeverity.HIGH,
                title=f"High-risk call detected: {call_id}",
                description=f"Risk score: {risk_score:.2f}. Findings: {'; '.join(findings)}",
                affected_resource=call_id,
                recommended_action="Review call and investigate source",
            )

        return {
            "call_id": call_id,
            "direction": direction,
            "risk_score": min(risk_score, 1.0),
            "findings": findings,
            "media_encrypted": media_encrypted,
            "pqc_enabled": pqc_enabled,
            "recommended_actions": self._get_call_recommendations(findings),
        }

    async def _monitor_signaling(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Monitor SIP signaling for anomalies."""
        messages = payload.get("messages", [])
        results = []

        for msg in messages:
            method = msg.get("method", "")
            call_id = msg.get("call_id", "")

            # Track call state
            if call_id not in self._active_calls:
                self._active_calls[call_id] = {"state": "new", "messages": []}
            self._active_calls[call_id]["messages"].append(method)

            # Detect out-of-order signaling
            state = self._active_calls[call_id]["state"]
            if method == "BYE" and state == "new":
                results.append({
                    "call_id": call_id,
                    "anomaly": "BYE without INVITE - possible tear-down attack",
                    "severity": "high",
                })

            if method == "INVITE":
                self._active_calls[call_id]["state"] = "invited"
            elif method == "ACK":
                self._active_calls[call_id]["state"] = "established"
            elif method == "BYE":
                self._active_calls[call_id]["state"] = "terminated"

        return {"monitored_messages": len(messages), "anomalies": results}

    async def _detect_anomaly(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Detect call pattern anomalies."""
        agent_id = payload.get("agent_id", "")
        time_window = payload.get("time_window_minutes", 60)
        calls = payload.get("calls", [])

        anomalies = []

        # Check call volume spikes
        call_count = len(calls)
        avg_calls = payload.get("avg_calls_per_window", 20)
        if call_count > avg_calls * 3:
            anomalies.append({
                "type": "volume_spike",
                "description": f"Call volume ({call_count}) exceeds 3x average ({avg_calls})",
                "severity": "high",
            })

        # Check for unusual destinations
        international_calls = [c for c in calls if c.get("international", False)]
        if len(international_calls) > call_count * 0.5 and call_count > 5:
            anomalies.append({
                "type": "international_pattern",
                "description": f"{len(international_calls)}/{call_count} calls are international",
                "severity": "high",
            })

        # Check for short duration calls (war dialing pattern)
        short_calls = [c for c in calls if c.get("duration_seconds", 0) < 3]
        if len(short_calls) > 10:
            anomalies.append({
                "type": "war_dialing",
                "description": f"{len(short_calls)} calls with <3s duration",
                "severity": "critical",
            })

        for anomaly in anomalies:
            if anomaly["severity"] in ("critical", "high"):
                self.generate_alert(
                    severity=AlertSeverity.HIGH if anomaly["severity"] == "high" else AlertSeverity.CRITICAL,
                    title=f"Call anomaly: {anomaly['type']}",
                    description=anomaly["description"],
                    affected_resource=agent_id,
                )

        return {"agent_id": agent_id, "calls_analyzed": call_count, "anomalies": anomalies}

    def _get_call_recommendations(self, findings: List[str]) -> List[str]:
        """Get recommendations based on findings."""
        recommendations = []
        for finding in findings:
            if "unencrypted" in finding.lower():
                recommendations.append("Enable SRTP for media encryption")
            if "spoofing" in finding.lower():
                recommendations.append("Enable SIP digest authentication")
            if "loop" in finding.lower():
                recommendations.append("Implement Max-Forwards check and SIP loop detection")
        return recommendations


