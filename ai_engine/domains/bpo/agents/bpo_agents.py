class FraudDetectionAgent(BaseBPOAgent):
    """
    Toll fraud and social engineering detection.

    Capabilities:
    - Toll fraud pattern detection (premium rate, IRSF, wangiri)
    - Social engineering attempt detection
    - Call forwarding fraud detection
    - PBX hacking attempt detection
    - Real-time fraud scoring
    """

    def __init__(self, config: Optional[BPOAgentConfig] = None):
        if config is None:
            config = BPOAgentConfig(agent_type=BPOAgentType.FRAUD_DETECTION)
        super().__init__(config)

        # High-risk country codes (premium rate / IRSF targets)
        self._high_risk_prefixes = {
            "+960", "+675", "+676", "+677", "+678", "+679",  # Pacific islands
            "+682", "+683", "+685", "+686", "+687", "+688",  # More Pacific
            "+252", "+253", "+291", "+297",  # Africa
            "+881", "+882",  # Satellite
        }

        self._premium_prefixes = {
            "+44870", "+44871", "+44872", "+44900", "+44901", "+44902",  # UK premium
            "+1900",  # US premium
        }

    async def _execute_task(self, task_type: str, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Execute fraud detection tasks."""
        if task_type == TaskType.DETECT_TOLL_FRAUD.value:
            return await self._detect_toll_fraud(payload)
        elif task_type == TaskType.ANALYZE_CALL_PATTERN.value:
            return await self._analyze_call_pattern(payload)
        elif task_type == TaskType.DETECT_SOCIAL_ENGINEERING.value:
            return await self._detect_social_engineering(payload)
        else:
            raise ValueError(f"Unknown task type: {task_type}")

    async def _detect_toll_fraud(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Detect toll fraud indicators."""
        destination = payload.get("destination", "")
        call_duration = payload.get("duration_seconds", 0)
        time_of_day = payload.get("hour_of_day", 12)
        agent_id = payload.get("agent_id", "")

        fraud_indicators = []
        fraud_score = 0.0

        # Check high-risk destinations
        for prefix in self._high_risk_prefixes:
            if destination.startswith(prefix):
                fraud_indicators.append(f"High-risk destination: {prefix}")
                fraud_score += 0.5
                break

        # Check premium rate numbers
        for prefix in self._premium_prefixes:
            if destination.startswith(prefix):
                fraud_indicators.append(f"Premium rate number: {prefix}")
                fraud_score += 0.6
                break

        # Off-hours calling (potential PBX compromise)
        if time_of_day < 6 or time_of_day > 22:
            fraud_indicators.append("Off-hours international call")
            fraud_score += 0.2

        # Unusually long calls to risky destinations
        if call_duration > 3600 and fraud_score > 0:
            fraud_indicators.append(f"Extended duration: {call_duration}s to suspicious destination")
            fraud_score += 0.2

        if fraud_score >= 0.7:
            self.generate_alert(
                severity=AlertSeverity.CRITICAL,
                title=f"Toll fraud detected: {destination}",
                description=f"Fraud score: {fraud_score:.2f}. {'; '.join(fraud_indicators)}",
                affected_resource=agent_id or destination,
                recommended_action="Block call and investigate immediately",
            )

        return {
            "destination": destination,
            "fraud_score": min(fraud_score, 1.0),
            "fraud_indicators": fraud_indicators,
            "action": "block" if fraud_score >= 0.7 else "allow" if fraud_score < 0.3 else "review",
        }

    async def _analyze_call_pattern(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Analyze call patterns for fraud indicators."""
        calls = payload.get("calls", [])
        time_window = payload.get("time_window_hours", 24)

        patterns = {
            "total_calls": len(calls),
            "unique_destinations": len(set(c.get("destination", "") for c in calls)),
            "international_ratio": 0.0,
            "avg_duration": 0.0,
            "off_hours_ratio": 0.0,
        }

        if calls:
            intl_count = sum(1 for c in calls if c.get("international", False))
            patterns["international_ratio"] = intl_count / len(calls)

            durations = [c.get("duration_seconds", 0) for c in calls]
            patterns["avg_duration"] = sum(durations) / len(durations) if durations else 0

            off_hours = sum(1 for c in calls if c.get("hour_of_day", 12) < 6 or c.get("hour_of_day", 12) > 22)
            patterns["off_hours_ratio"] = off_hours / len(calls)

        # Wangiri detection (many short calls)
        short_calls = [c for c in calls if c.get("duration_seconds", 0) < 2]
        if len(short_calls) > 20:
            patterns["wangiri_indicator"] = True
            self.generate_alert(
                severity=AlertSeverity.HIGH,
                title="Wangiri fraud pattern detected",
                description=f"{len(short_calls)} calls with <2s duration in {time_window}h window",
            )

        return patterns

    async def _detect_social_engineering(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Detect social engineering indicators in call metadata."""
        caller_id = payload.get("caller_id", "")
        call_reason = payload.get("call_reason", "")
        requests_made = payload.get("requests_made", [])

        se_indicators = []
        risk_score = 0.0

